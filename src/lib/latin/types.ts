/**
 * Номер ударного слога **с конца**: 1 — единственный слог, 2 — предпоследний,
 * 3 — третий от конца. Других значений в медицинской латыни не бывает: дальше
 * третьего слога ударение не уходит.
 */
export type StressPos = 1 | 2 | 3;

/** Латинское слово в нижнем регистре → номер ударного слога с конца. */
export type StressMap = Record<string, StressPos>;

/**
 * Ядро слога: гласная (`a`) или диграф/дифтонг (`ae`, `au`, `eu`) и его индекс
 * в латинском написании слова. Слогов в слове ровно столько, сколько ядер,
 * поэтому делить слово на границы согласных не нужно.
 */
export interface Syllable {
  nucleus: string;
  start: number;
}
