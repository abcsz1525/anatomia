const OVERRIDE_BY_ID = new Map<string, SystemId>(
  Object.entries(SYSTEM_OVERRIDES).flatMap(([system, ids]) => ids.map((id) => [id, system as SystemId] as const)),
);

export function applySystemOverrides(manifest: AtlasManifest): AtlasManifest {
  return {
    ...manifest,
    parts: manifest.parts.map((p) => {
      const system = OVERRIDE_BY_ID.get(p.id);
      return system ? { ...p, system } : p;
    }),
  };
}
